import type { Edge, Node } from '@xyflow/react';

export type NodeStatus = 'mastered' | 'weak' | 'next';

export interface QuizQuestion {
  id: string;
  question: string;
  options: string[];
  correctIndex: number;
  topic: string;
}

export interface QuizResult {
  totalQuestions: number;
  correctAnswers: number;
  strengths: string[];
  weaknesses: string[];
}

export interface PracticeQuestion {
  question: string;
  options: string[];
  correctIndex: number;
}

// React Flow v12 requires node data to be assignable to Record<string, unknown>.
export interface RoadmapNodeData extends Record<string, unknown> {
  label: string;
  status: NodeStatus;
  resourceTitle: string;
  resourceUrl: string;
  practiceQuestion: PracticeQuestion;
}

export type RoadmapNode = Node<RoadmapNodeData, 'custom'>;
export type RoadmapEdge = Edge;

export interface APIRequestPayload {
  strengths: string[];
  weaknesses: string[];
}

export interface APIResponsePayload {
  nodes: RoadmapNode[];
  edges: RoadmapEdge[];
  /** 'gemini' when generated by the model, 'mock' when the demo fallback was used. */
  source: 'gemini' | 'mock';
  /** Human-readable note when the fallback was used. */
  warning?: string;
}

export interface APIErrorPayload {
  error: string;
}
